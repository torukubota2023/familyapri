def line_chart():
    W, H, L, B, T, R = 1740, 470, 110, 60, 20, 330
    series = [
        ("購入・固定2％", [sum(buy_monthly(30, "固定2%")[y*12:(y+1)*12]) / 12 for y in range(30)], "var(--buy)", ""),
        ("購入・固定3.5％", [sum(buy_monthly(30, "固定3.5%")[y*12:(y+1)*12]) / 12 for y in range(30)], "var(--buy)", "10 8"),
        ("賃貸14万・年2％上昇", [14 * 1.02 ** y for y in range(30)], "var(--rent)", "10 8"),
        ("賃貸14万・年0.5％上昇", [14 * 1.005 ** y for y in range(30)], "var(--rent)", ""),
    ]
    ymax = 35
    x = lambda i: L + (W - L - R) * i / 29
    y = lambda v: T + (H - T - B) * (1 - v / ymax)
    g = [f'<svg width="{W}" height="{H}" font-size="26" font-family="IPAPGothic">']
    for v in range(0, ymax + 1, 5):
        g.append(f'<line x1="{L}" x2="{W-R}" y1="{y(v)}" y2="{y(v)}" stroke="#d9d3c5"/>'
                 f'<text x="{L-14}" y="{y(v)+9}" text-anchor="end" fill="#5b6475">{v}万</text>')
    for yr in (1, 5, 10, 15, 20, 25, 30):
        g.append(f'<text x="{x(yr-1)}" y="{H-B+40}" text-anchor="middle" fill="#5b6475">{yr}年目</text>')
    g.append(f'<line x1="{x(19.5)}" x2="{x(19.5)}" y1="{T}" y2="{H-B}" stroke="#999" stroke-dasharray="4 6"/>'
             f'<text x="{x(19.5)+10}" y="{T+30}" fill="#5b6475">ローン完済</text>')
    for name, vals, col, dash in series:
        pts = " ".join(f"{x(i):.1f},{y(v):.1f}" for i, v in enumerate(vals))
        g.append(f'<polyline points="{pts}" fill="none" stroke="{col}" stroke-width="6" stroke-dasharray="{dash}"/>')
        if name.startswith("購入"):
            dy = -16 if "3.5" in name else 40
            g.append(f'<text x="{x(0)}" y="{y(vals[0])+dy}" fill="{col}">{name}</text>')
            if "2％" in name:
                g.append(f'<text x="{x(29)+14}" y="{y(vals[-1])+9}" fill="{col}">購入（完済後は維持費のみ）</text>')
        else:
            g.append(f'<text x="{x(29)+14}" y="{y(vals[-1])+9}" fill="{col}">{name}</text>')
    g.append("</svg>")
    return "".join(g)


def stack_bars(n):
    t = totals(n, "固定2%")
    parts = [("頭金＋諸費用", t["upfront"], "#e9c46a"), ("ローン元本", t["principal"], "#c8553d"),
             ("利息", t["interest"], "#e07a5f"), ("維持費", t["maint"], "#9c6644")]
    scale = 0.165
    out = ['<div style="display:flex;flex-direction:column;gap:26px;font-size:30px">']
    seg = "".join(f'<div style="width:{v*scale}px;background:{c};height:84px;display:flex;align-items:center;'
                  f'justify-content:center;color:#fff;font-size:26px">{nm}<br>{man(v)}</div>' for nm, v, c in parts)
    out.append(f'<div style="display:flex;align-items:center;gap:20px"><div style="width:220px">購入の支出</div>{seg}'
               f'<div style="margin-left:14px">計 <b>{man(t["buy_gross"])}</b></div></div>')
    for sale in (2000, 3000, 4000):
        net = t["buy_gross"] - sale
        out.append(f'<div style="display:flex;align-items:center;gap:20px"><div style="width:220px">売却{sale//1000}千万なら</div>'
                   f'<div style="width:{net*scale}px;height:52px;background:#c8553d;opacity:.75"></div>'
                   f'<div style="width:{sale*scale}px;height:52px;border:3px dashed #c8553d;color:#c8553d;font-size:24px;'
                   f'display:flex;align-items:center;justify-content:center">家が残る −{man(sale)}</div>'
                   f'<div>実質 <b class="buy">{man(net)}</b></div></div>')
    r = t["rent_gross"]
    out.append(f'<div style="display:flex;align-items:center;gap:20px"><div style="width:220px" class="rent">賃貸14万</div>'
               f'<div style="width:{r*scale}px;height:84px;background:#2a6f97;color:#fff;font-size:26px;display:flex;'
               f'align-items:center;justify-content:center">家賃＋追加費用300万</div><div>計 <b class="rent">{man(r)}</b></div></div>')
    out.append("</div>")
    return "".join(out)


def be_table(n):
    rows = [("固定2％", "固定2%"), ("変動 2→3％", "変動 2%→3%"), ("変動 2→4％", "変動 2%→4%"), ("固定3.5％", "固定3.5%")]
    h = ['<table style="font-size:44px"><tr><th>ローン</th><th>家賃上昇</th><th>売却2,000万</th><th>売却3,000万</th><th>売却4,000万</th></tr>']
    for i, (lab, k) in enumerate(rows):
        for g in (0.005, 0.02):
            cells = "".join(f"<td>{f1(be(n, s, g, k))}万</td>" for s in (2000, 3000, 4000))
            h.append(f'<tr data-s="{1 if i == 0 else 3 if i < 3 else 4}"><td>{lab}</td><td>年{g*100:.1f}％</td>{cells}</tr>')
    h.append("</table>")
    return "".join(h)


